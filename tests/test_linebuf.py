"""Проверка обработки '\\r' в консоли (без Qt)."""

import sys

sys.path.insert(0, "/home/user/music_suite")

from musicsuite.linebuf import LineBuffer


def check(name, chunks, expected):
    buf = LineBuffer()
    for chunk in chunks:
        buf.feed(chunk)
    actual = buf.text()
    status = "OK " if actual == expected else "FAIL"
    print(f"[{status}] {name}")
    if actual != expected:
        print(f"    ожидалось: {expected!r}")
        print(f"    получено : {actual!r}")


check("прогресс-бар в одной строке",
      ["Загрузка 0%", "\rЗагрузка 33%", "\rЗагрузка 66%", "\rЗагрузка 100%", "\n"],
      "Загрузка 100%\n")

check("строка завершена переводом строки",
      ["Трек 1 ", "\rТрек 1 OK", "\nСледующая\n"],
      "Трек 1 OK\nСледующая\n")

check("tqdm-подобный вывод с хвостом",
      ["50%|#####     | 5/10", "\r100%|##########| 10/10", "\n"],
      "100%|##########| 10/10\n")

check("обычные print подряд",
      ["Первая строка\n", "Вторая строка\n"],
      "Первая строка\nВторая строка\n")

check("длинная строка короче предыдущей",
      ["abcdefghij", "\rXY"],
      "XY")

check("смешанный вывод yamd",
      ["Исполнитель - Трек", "\rИсполнитель - Трек | 1 ЗАГРУЗКА | 42%",
       "\rИсполнитель - Трек | 1 OK (MP3 320k)", "\n"],
      "Исполнитель - Трек | 1 OK (MP3 320k)\n")

check("несколько кусков без перевода строки",
      ["ab", "cd", "\refgh"],
      "efgh")

check("\r\n как перевод строки",
      ["Строка один\r\nСтрока два\r\n"],
      "Строка один\nСтрока два\n")

# --- регрессия: регрессии, найденные при аудите ---

check("\r\n разрезан между порциями",
      ["Строка один\r", "\nСтрока два\n"],
      "Строка один\nСтрока два\n")

check("\r в конце порции не теряет строку",
      ["Трек загружен 100%\r", "\nСледующая\n"],
      "Трек загружен 100%\nСледующая\n")

check("хвостовой \\r виден в text() до продолжения",
      ["Текст\r"],
      "Текст\r")

check("незавершённый прогресс сохраняется",
      ["Скачивание 42%"],
      "Скачивание 42%")

print("\nГотово.")
