"""Версия приложения: единый источник для окна, README и «О программе».

Как устроена нумерация
----------------------
Версия собирается из двух частей:

    APP_VERSION = "1.9.28"
                   ^^^ ^^
                   |   └── BUILD — номер сборки, совпадает с номером
                   |       архива (v28 → build 28)
                   └────── MAJOR.MINOR — крупная и мелкая версия

Номер сборки увеличивается при каждой выкладке архива, поэтому версию
в заголовке окна и имя архива можно сверить напрямую: если в заголовке
«1.9.28», архив называется v28.

Менять версию нужно ТОЛЬКО здесь. Заголовок окна, «О программе»,
QApplication.applicationVersion() и README берут значения отсюда, так
что расхождений между ними быть не может.
"""

from __future__ import annotations

# ---------------------------------------------------------------------------
# Единственное место, где задаётся версия
# ---------------------------------------------------------------------------

MAJOR = 1
MINOR = 9

# Номер сборки = номер архива. Увеличивать при каждой выкладке.
BUILD = 31

APP_NAME = "MusEdit"
APP_VERSION = f"{MAJOR}.{MINOR}.{BUILD}"
APP_TITLE = f"{APP_NAME} {APP_VERSION}"

# Полное имя с типом сборки — для «О программе» и README
APP_VERSION_FULL = f"{APP_VERSION} (сборка {BUILD})"

ORGANIZATION = "Dmtr Klpv, 2026"


def version_tuple() -> tuple[int, int, int]:
    """Версия как кортеж чисел — удобно сравнивать."""
    return MAJOR, MINOR, BUILD


def archive_name() -> str:
    """Базовое имя архива для этой сборки, без расширения и метки времени."""
    return f"{APP_NAME.replace(' ', '_')}_{APP_VERSION}_v{BUILD}"
